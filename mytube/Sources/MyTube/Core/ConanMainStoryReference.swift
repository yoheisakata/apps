    /// タイトル文字列(`VideoItem.title`)の話数トークンから話数の範囲を取り出す。
    /// `0130`のような単一話数、`0309-311`/`0491-0504`のような範囲(1本のファイルに
    /// 複数話数がまとまっている)、どちらも`ClosedRange<Int>`で返す。数字で始まらない
    /// トークン(`Special`/`Movie`/`SP1`等)は`nil`。
    static func episodeRange(inTitle title: String) -> ClosedRange<Int>? {
        let components = title.components(separatedBy: " - ")
        guard components.count >= 2 else { return nil }
        let parts = components[1].split(separator: "-")
        switch parts.count {
        case 1:
            guard let value = Int(parts[0]) else { return nil }
            return value...value
        case 2:
            guard let start = Int(parts[0]), let end = Int(parts[1]), start <= end else { return nil }
            return start...end
        default:
            return nil
        }
    }

    /// `range`に含まれるどの話数がこのテーブルに載っていても、その分すべてのタグを
    /// 重複無く合わせて返す(`0491-0504`のように複数話数が1本のファイルにまとまっている
    /// 場合、range内の全話数ぶんのタグを合算する)。
    static func tags(forEpisodeRange range: ClosedRange<Int>) -> [String] {
        var result: [String] = []
        for episode in range {
            guard let tags = tagsByEpisode[episode] else { continue }
            for tag in tags where !result.contains(tag) {
                result.append(tag)
            }
        }
        return result
    }

    static func containsAnyEpisode(in range: ClosedRange<Int>) -> Bool {
        range.contains { tagsByEpisode[$0] != nil }
    }
